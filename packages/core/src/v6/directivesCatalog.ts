import type {
  CommandCardEffect,
  DefenseSystem,
  DirectiveTendency,
  DirectiveZone,
  EventHookRule,
  FormationName,
  ImmunityFlags,
  TacticalStyle,
} from '@fm-league/engine';
import type { V6DirectiveDef, V6SatelliteDef } from './types';

type RawDirTuple = [
  id: string,
  name: string,
  zone: DirectiveZone,
  tendency: DirectiveTendency,
  route: V6DirectiveDef['route'],
  benefitSummary: string,
  riskSummary: string,
  baseEffect: Omit<CommandCardEffect, 'id' | 'name' | 'durationMinutes'>,
  satA: [label: string, desc: string, patch?: Partial<V6SatelliteDef>],
  satB: [label: string, desc: string, extraEffect?: Partial<CommandCardEffect>, extraImmunity?: ImmunityFlags],
  satC: [label: string, desc: string, hooks?: EventHookRule[], extraEffect?: Partial<CommandCardEffect>, extraImmunity?: ImmunityFlags],
];

function buildDir(
  t: RawDirTuple,
  meta: { source: V6DirectiveDef['source']; style?: TacticalStyle; formation?: FormationName; defenseSystem?: DefenseSystem }
): V6DirectiveDef {
  const [id, name, zone, tendency, route, benefitSummary, riskSummary, baseEffect, sA, sB, sC] = t;
  const tpCost: 1 | 2 | 3 = route === 'steady' ? 1 : route === 'fusion' ? 3 : 2;
  const unlockCost = route === 'steady' ? 1 : route === 'fusion' ? 3 : 2;
  return {
    id,
    name,
    source: meta.source,
    style: meta.style,
    formation: meta.formation,
    defenseSystem: meta.defenseSystem,
    zone,
    tendency,
    route,
    tpCost,
    unlockCost,
    durationMinutes: 20,
    benefitSummary,
    riskSummary,
    baseEffect: {
      ...baseEffect,
      zone,
      tendency,
      tpCost,
      benefitSummary,
      riskSummary,
    },
    satellites: {
      A: { key: 'A', label: sA[0], desc: sA[1], cost: 1, halveRisk: true, ...(sA[2] ?? {}) },
      B: { key: 'B', label: sB[0], desc: sB[1], cost: 1, extraEffect: sB[2], extraImmunity: sB[3] },
      C: { key: 'C', label: sC[0], desc: sC[1], cost: 2, extraHooks: sC[2], extraEffect: sC[3], extraImmunity: sC[4] },
    },
  };
}

